const rowsOf = (matrix) => matrix.dark.map((row) => row.map((d) => (d ? '1' : '0')).join(''));

for (const { text, rows } of REFERENCE) {
  const version = (rows.length - 17) / 4;
  test(`matches the reference symbol for a ${text.length}-byte payload (version ${version})`, () => {
    const matrix = encodeQr(text);
    assert.equal(matrix.size, rows.length);
    assert.deepEqual(rowsOf(matrix), rows);
  });
}

test('a booking token (24 random bytes, base64url) fits in a 29x29 version 3 symbol', () => {
  const token = 'Zx81_kQ0pLmN2bVc7YtR4eWq9sA3uJ6H';
  assert.equal(token.length, 32);
  assert.equal(encodeQr(token).size, 29);
});

test('the three finder patterns are always in place', () => {
  const { size, dark } = encodeQr('finder check');
  const finderRow = [true, true, true, true, true, true, true];
  for (const [x, y] of [
    [0, 0],
    [size - 7, 0],
    [0, size - 7],
  ]) {
    assert.deepEqual(dark[y].slice(x, x + 7), finderRow, `top edge at ${x},${y}`);
    assert.deepEqual(dark[y + 6].slice(x, x + 7), finderRow, `bottom edge at ${x},${y}`);
    assert.equal(dark[y + 1][x + 1], false, `inner ring at ${x},${y}`);
    assert.equal(dark[y + 3][x + 3], true, `center at ${x},${y}`);
  }
});

test('the same text always gives the same symbol', () => {
  assert.deepEqual(rowsOf(encodeQr('stable')), rowsOf(encodeQr('stable')));
});

test('payloads longer than version 10 holds are rejected', () => {
  assert.throws(() => encodeQr('x'.repeat(214)), RangeError);
  assert.doesNotThrow(() => encodeQr('x'.repeat(213)));
});

test('qrPath draws one unit square per dark module, offset by the quiet zone', () => {
  const matrix = encodeQr('path');
  const darkCount = matrix.dark.flat().filter(Boolean).length;
  const path = qrPath(matrix, 4);
  assert.equal(path.split('M').length - 1, darkCount);
  assert.ok(path.startsWith('M4,4h1v1h-1z'), 'top-left finder corner shifted by the border');
});
